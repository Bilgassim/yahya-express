// Fonctions d'application et de bascule de langue
function getInitialLanguage() {
  var saved = localStorage.getItem('yahya_lang');
  if (saved === 'fr' || saved === 'ar') {
    return saved;
  }
  // Detection automatique de la langue du systeme client
  var sysLang = (navigator.language || navigator.userLanguage || 'fr').toLowerCase();
  if (sysLang.indexOf('ar') === 0) {
    return 'ar';
  }
  return 'fr';
}

function applyLanguage(lang) {
  if (lang !== 'fr' && lang !== 'ar') lang = 'fr';
  localStorage.setItem('yahya_lang', lang);

  // Direction du document
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

  var dict = translations[lang];
  if (!dict) return;

  // Traduction des elements textes
  var elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Traduction des placeholders
  var phElements = document.querySelectorAll('[data-i18n-ph]');
  phElements.forEach(function (el) {
    var key = el.getAttribute('data-i18n-ph');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Mise a jour du libelle du bouton de bascule
  var toggleBtns = document.querySelectorAll('.lang-toggle-btn');
  toggleBtns.forEach(function (btn) {
    btn.textContent = dict['lang_switch'] || (lang === 'ar' ? 'Français' : 'العربية');
  });
}

function toggleLanguage() {
  var current = localStorage.getItem('yahya_lang') || getInitialLanguage();
  var next = (current === 'ar') ? 'fr' : 'ar';
  applyLanguage(next);
}

document.addEventListener('DOMContentLoaded', function () {
  var lang = getInitialLanguage();
  applyLanguage(lang);

  // Ecouteur sur les boutons de changement de langue
  var toggleBtns = document.querySelectorAll('.lang-toggle-btn');
  toggleBtns.forEach(function (btn) {
    btn.addEventListener('click', function (e) {
      e.preventDefault();
      toggleLanguage();
    });
  });
});
